#!/usr/bin/env python3
"""Generate ChineseSpeciesNamesGen.kt from a pinned PokeAPI species names CSV.

Download data/v2/csv/pokemon_species_names.csv from PokeAPI/pokeapi at
6b8db7f3cb31cfaa37cb74e5c3edff124bcba5ce, then run:
    python scripts/gen_zh_species.py PATH/TO/pokemon_species_names.csv [--check]
The SHA-256 check makes a changed source fail rather than silently changing names.
"""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'app/src/main/kotlin/com/pokedaisy/app/companion/data/ChineseSpeciesNamesGen.kt'
SHA256 = '820cde17074cdb1c2b0595c997fb8f998e773bd5da3bb525dec85703c86c5fd9'
COMMIT = '6b8db7f3cb31cfaa37cb74e5c3edff124bcba5ce'
# PokeAPI's zh-hans rows contain three traditional characters. The corrected
# forms are confirmed by https://dex.pokemon.cn/play/pokedex/0312,
# https://pokedex.pokemon.cn/play/pokedex/0973 and /0990 respectively.
SIMPLIFIED_CORRECTIONS = {312: '负电拍拍', 973: '缠红鹤', 990: '铁辙迹'}


def kotlin_string(s):
    return json.dumps(s, ensure_ascii=False).replace('$', r'\$')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('csv', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = args.csv.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        parser.error('unexpected PokeAPI CSV checksum')
    entries = {}
    for row in csv.DictReader(io.StringIO(data.decode('utf-8-sig'), newline='')):
        number, lang, name = int(row['pokemon_species_id']), int(row['local_language_id']), row['name']
        if not 1 <= number <= 1025 or not name:
            continue
        if '|' in name or '\n' in name or '\r' in name:
            parser.error(f'unsupported delimiter in name for #{number}')
        record = entries.setdefault(number, {'zh': None, 'aliases': set()})
        record['aliases'].add(name)
        if lang == 12:
            record['zh'] = name
    if set(entries) != set(range(1, 1026)) or any(not e['zh'] for e in entries.values()):
        parser.error('missing National Dex entries or Simplified Chinese names')
    lines = [
        'package com.pokedaisy.app.companion.data', '',
        '// Generated by scripts/gen_zh_species.py; PokeAPI/pokeapi @ ' + COMMIT,
        '// pokemon_species_names.csv, BSD 3-Clause (third_party/licenses/PokeAPI-BSD-3-Clause.txt).',
        '// Each row: Simplified Chinese name, then source names that verify this national number.',
        'internal val chineseSpeciesNames: Array<String> = arrayOf(',
        '    "",',
    ]
    for number in range(1, 1026):
        entry = entries[number]
        chinese = SIMPLIFIED_CORRECTIONS.get(number, entry['zh'])
        names = [chinese] + sorted(entry['aliases'] - {chinese})
        lines.append(f'    {kotlin_string("|".join(names))}, // {number}')
    lines += [')', '']
    output = '\n'.join(lines)
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != output:
            raise SystemExit('Chinese species table is stale')
        print('Chinese species table is up to date')
    else:
        OUTPUT.write_text(output, encoding='utf-8', newline='\n')
        print(f'Wrote {len(entries)} Chinese species names')


if __name__ == '__main__':
    main()
